// 5. Listar produtos
app.MapGet("/api/produtos", async () =>
{
    var lista = new List<Produto>();

    await using var db = new NpgsqlConnection(connectionString);
    await db.OpenAsync();

    const string sql = """
        SELECT id, nome, cat, preco, estoque, img
        FROM produtos ORDER BY id
        """;

    await using var cmd = new NpgsqlCommand(sql, db);
    await using var reader = await cmd.ExecuteReaderAsync();

    while (await reader.ReadAsync())
    {
        lista.Add(new Produto
        {
            Id = reader.GetInt32(0),
            Nome = reader.GetString(1),
            Cat = reader.GetString(2),
            Preco = reader.GetDecimal(3),
            Estoque = reader.GetInt32(4),
            Img = reader.GetString(5)
        });
    }

    return Results.Ok(lista);
});

// 6. Listar pedidos
app.MapGet("/api/pedidos", async () =>
{
    var lista = new List<Pedido>();

    await using var db = new NpgsqlConnection(connectionString);
    await db.OpenAsync();

    const string sql = """
        SELECT id, itens, endereco, total, status
        FROM pedidos ORDER BY id
        """;

    await using var cmd = new NpgsqlCommand(sql, db);
    await using var reader = await cmd.ExecuteReaderAsync();

    while (await reader.ReadAsync())
    {
        lista.Add(new Pedido
        {
            Id = reader.GetInt32(0),
            Itens = JsonSerializer.Deserialize<List<Produto>>(
                reader.GetString(1)) ?? new List<Produto>(),
            Endereco = reader.GetString(2),
            Total = reader.GetDecimal(3),
            Status = reader.GetString(4)
        });
    }

    return Results.Ok(lista);
});

// 7. Criar e salvar pedido
app.MapPost("/api/pedidos", async (Pedido novoPedido) =>
{
    novoPedido.Status = "PENDENTE";
    novoPedido.Itens ??= new List<Produto>();

    await using var db = new NpgsqlConnection(connectionString);
    await db.OpenAsync();

    const string sql = """
        INSERT INTO pedidos (itens, endereco, total, status)
        VALUES (@itens, @endereco, @total, @status)
        RETURNING id
        """;

    await using var cmd = new NpgsqlCommand(sql, db);

    cmd.Parameters.AddWithValue(
        "itens",
        NpgsqlDbType.Jsonb,
        JsonSerializer.Serialize(novoPedido.Itens));

    cmd.Parameters.AddWithValue("endereco", novoPedido.Endereco);
    cmd.Parameters.AddWithValue("total", novoPedido.Total);
    cmd.Parameters.AddWithValue("status", novoPedido.Status);

    novoPedido.Id = (int)(await cmd.ExecuteScalarAsync()
        ?? throw new InvalidOperationException(
            "Nao foi possivel criar o pedido."));

    return Results.Ok(novoPedido);
});

// 8. Entregar pedido e atualizar estoque
app.MapPost("/api/pedidos/{id}/entregar", async (int id) =>
{
    await using var db = new NpgsqlConnection(connectionString);
    await db.OpenAsync();

    await using var transaction = await db.BeginTransactionAsync();

    try
    {
        const string selectSql = """
            SELECT itens, status
            FROM pedidos
            WHERE id = @id
            FOR UPDATE
            """;

        string itensJson;
        string status;

        await using (var cmd = new NpgsqlCommand(
            selectSql, db, transaction))
        {
            cmd.Parameters.AddWithValue("id", id);

            await using var reader = await cmd.ExecuteReaderAsync();

            if (!await reader.ReadAsync())
            {
                return Results.BadRequest(
                    "Pedido nao encontrado ou ja enviado.");
            }

            itensJson = reader.GetString(0);
            status = reader.GetString(1);
        }

        if (status != "PENDENTE")
        {
            return Results.BadRequest(
                "Pedido nao encontrado ou ja enviado.");
        }

        var itens = JsonSerializer.Deserialize<List<Produto>>(
            itensJson) ?? new List<Produto>();

        foreach (var item in itens)
        {
            const string updateEstoque = """
                UPDATE produtos
                SET estoque = GREATEST(0, estoque - 1)
                WHERE id = @id
                """;

            await using var cmd = new NpgsqlCommand(
                updateEstoque, db, transaction);

            cmd.Parameters.AddWithValue("id", item.Id);
            await cmd.ExecuteNonQueryAsync();
        }

        const string updatePedido = """
            UPDATE pedidos SET status = 'ENVIADO'
            WHERE id = @id
            """;

        await using (var cmd = new NpgsqlCommand(
            updatePedido, db, transaction))
        {
            cmd.Parameters.AddWithValue("id", id);
            await cmd.ExecuteNonQueryAsync();
        }

        await transaction.CommitAsync();

        return Results.Ok(new
        {
            mensagem = "Estoque atualizado!",
            pedido = new { id, status = "ENVIADO" }
        });
    }
    catch
    {
        await transaction.RollbackAsync();
        throw;
    }
});

// 9. Atualizar estoque manualmente
app.MapPatch("/api/produtos/{id}", async (
    int id, [FromBody] int novaQtd) =>
{
    if (novaQtd < 0)
    {
        return Results.BadRequest(
            "O estoque nao pode ser negativo.");
    }

    await using var db = new NpgsqlConnection(connectionString);
    await db.OpenAsync();

    const string sql = """
        UPDATE produtos SET estoque = @estoque
        WHERE id = @id
        RETURNING id, nome, cat, preco, estoque, img
        """;

    await using var cmd = new NpgsqlCommand(sql, db);
    cmd.Parameters.AddWithValue("id", id);
    cmd.Parameters.AddWithValue("estoque", novaQtd);

    await using var reader = await cmd.ExecuteReaderAsync();

    if (!await reader.ReadAsync())
    {
        return Results.NotFound();
    }

    var produto = new Produto
    {
        Id = reader.GetInt32(0),
        Nome = reader.GetString(1),
        Cat = reader.GetString(2),
        Preco = reader.GetDecimal(3),
        Estoque = reader.GetInt32(4),
        Img = reader.GetString(5)
    };

    return Results.Ok(produto);
});

