var builder = WebApplication.CreateBuilder(args);

// 1. Conexao segura com o Neon usando User Secrets
var rawConnection = builder.Configuration
    .GetConnectionString("PhantomWear");

if (string.IsNullOrWhiteSpace(rawConnection))
{
    throw new InvalidOperationException(
        "A conexao PhantomWear nao foi configurada.");
}

var uri = new Uri(rawConnection);
var credentials = uri.UserInfo.Split(':', 2);

if (credentials.Length != 2)
{
    throw new InvalidOperationException(
        "Formato da conexao PostgreSQL invalido.");
}

var connectionString = new NpgsqlConnectionStringBuilder
{
    Host = uri.Host,
    Port = uri.Port > 0 ? uri.Port : 5432,
    Username = Uri.UnescapeDataString(credentials[0]),
    Password = Uri.UnescapeDataString(credentials[1]),
    Database = Uri.UnescapeDataString(
        uri.AbsolutePath.TrimStart('/')),
    SslMode = SslMode.Require
}.ConnectionString;

// 2. Configuracao de porta para o Render
var port = Environment.GetEnvironmentVariable("PORT") ?? "8080";
builder.WebHost.UseUrls($"http://0.0.0.0:{port}");

builder.Services.AddCors(options =>
{
    options.AddDefaultPolicy(policy =>
        policy.AllowAnyOrigin()
              .AllowAnyHeader()
              .AllowAnyMethod());
});

var app = builder.Build();

app.UseDefaultFiles();
app.UseStaticFiles();
app.UseCors();

